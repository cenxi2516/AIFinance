def get_all_concept_names() -> list[str]:
    """收集映射表中所有概念板块名称（去重）"""
    names = set(MARKET_WIDE_CONCEPTS)
    for industry_cfg in INDUSTRY_SENTIMENT_MAP.values():
        for name in industry_cfg.get("parent_concepts", []):
            names.add(name)
        for sub_cfg in industry_cfg.get("sub_sectors", {}).values():
            for name in sub_cfg.get("concepts", []):
                names.add(name)
    return sorted(names)


def get_industry_keys() -> list[str]:
    """返回所有行业 key 列表"""
    return list(INDUSTRY_SENTIMENT_MAP.keys())


def get_sub_sector_keys(industry_key: str) -> list[str]:
    """返回指定行业的所有细分方向 key 列表"""
    cfg = INDUSTRY_SENTIMENT_MAP.get(industry_key, {})
    return list(cfg.get("sub_sectors", {}).keys())


def get_concepts_for_industry(industry_key: str) -> list[str]:
    """返回指定行业覆盖的所有概念板块名称（去重）"""
    cfg = INDUSTRY_SENTIMENT_MAP.get(industry_key, {})
    names = set(cfg.get("parent_concepts", []))
    for sub_cfg in cfg.get("sub_sectors", {}).values():
        names.update(sub_cfg.get("concepts", []))
    return sorted(names)


def get_concepts_for_sub_sector(industry_key: str, sub_key: str) -> list[str]:
    """返回指定细分方向的概念板块名称列表"""
    cfg = INDUSTRY_SENTIMENT_MAP.get(industry_key, {})
    sub = cfg.get("sub_sectors", {}).get(sub_key, {})
    return sub.get("concepts", [])


def get_linked_etfs(industry_key: str) -> list[str]:
    """返回指定行业关联的 ETF 代码列表"""
    cfg = INDUSTRY_SENTIMENT_MAP.get(industry_key, {})
    return cfg.get("linked_etfs", [])


def get_sentiment_level(score: float) -> dict:
    """根据综合情绪分返回等级信息"""
    for threshold, label, emoji, note in SENTIMENT_LEVELS:
        if score >= threshold:
            return {"label": label, "emoji": emoji, "note": note}
    return {"label": "极度悲观", "emoji": "🟢", "note": ""}
